// Coverage tracker: regenerates PROGRESS.md (totals, history, per-module and per-size coverage,
// closest near-misses, biggest unmatched functions) from functions.tsv + matched.tsv + nearmiss.tsv,
// and appends a row to progress.csv when the numbers changed.
//
//   node tools/progress.mjs              update PROGRESS.md (+ progress.csv if changed)
//   node tools/progress.mjs --backfill   rebuild progress.csv from the git history of matched.tsv
//
// It trusts matched.tsv; `node tools/check_all.mjs` is what re-verifies every entry.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const rows = f => existsSync(f) ? readFileSync(f, 'utf8').split('\n').filter(l => l.trim() && !l.startsWith('#')).map(l => l.trim().split('\t')) : [];
const fns = rows('functions.tsv').map(([a, s, n, m]) => ({ addr: a.toLowerCase(), size: +s, name: n, module: (m || '?').replace(/^~/, ''), inferred: (m || '').startsWith('~') }));
const byAddr = new Map(fns.map(f => [f.addr, f]));
const TOTAL_BYTES = fns.reduce((n, f) => n + f.size, 0);
// A matched row covers every function wholly inside [addr, addr+size): one source can span a genuine
// pair (e.g. a static object's _GLOBAL_.D + _GLOBAL_.I).
const exactSet = text => {
  const set = new Set();
  for (const l of text.split('\n')) {
    if (!l.trim() || l.startsWith('#')) continue;
    const [, a, s] = l.split('\t'), lo = parseInt(a, 16), hi = lo + (+s || 0);
    if (!byAddr.has(a?.toLowerCase())) continue;
    for (const f of fns) { const fa = parseInt(f.addr, 16); if (fa >= lo && fa + f.size <= hi) set.add(f.addr); }
  }
  return set;
};
const tally = set => ({ funcs: set.size, bytes: [...set].reduce((n, a) => n + byAddr.get(a).size, 0) });
const pct = (a, b) => (b ? (100 * a / b) : 0).toFixed(1);
const bar = (a, b, w = 20) => { const k = Math.round(w * a / (b || 1)); return '`' + '█'.repeat(k) + '░'.repeat(w - k) + '`'; };
const kb = n => n >= 1024 ? `${(n / 1024).toFixed(1)} KB` : `${n} B`;
const today = new Date().toISOString().slice(0, 10);
const CSV_HEAD = 'date,commit,exact_functions,total_functions,exact_bytes,total_bytes,percent_bytes';

if (process.argv.includes('--backfill')) {
  const log = execFileSync('git', ['log', '--reverse', '--format=%H %cs', '--', 'matched.tsv'], { encoding: 'utf8' }).trim().split('\n');
  const out = [CSV_HEAD];
  for (const line of log) {
    const [hash, date] = line.split(' ');
    const t = tally(exactSet(execFileSync('git', ['show', `${hash}:decomp/matched.tsv`], { encoding: 'utf8' })));
    out.push([date, hash.slice(0, 7), t.funcs, fns.length, t.bytes, TOTAL_BYTES, pct(t.bytes, TOTAL_BYTES)].join(','));
  }
  writeFileSync('progress.csv', out.join('\n') + '\n');
  console.log(`progress.csv rebuilt: ${out.length - 1} points`);
}

const exact = exactSet(readFileSync('matched.tsv', 'utf8'));
const T = tally(exact);
const near = rows('nearmiss.tsv').map(([src, a, s, tool, score]) => {
  const [g, w] = score.split('/').map(Number); return { src, addr: a.toLowerCase(), size: +s, score, frac: g / w };
}).filter(n => !exact.has(n.addr));

// history: append when the numbers changed since the last recorded row
let csv = existsSync('progress.csv') ? readFileSync('progress.csv', 'utf8').trim().split('\n') : [CSV_HEAD];
const last = csv.length > 1 ? csv[csv.length - 1].split(',') : null;
if (!last || +last[2] !== T.funcs || +last[4] !== T.bytes) {
  let head = '';
  try { head = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() + (execFileSync('git', ['status', '--porcelain', 'matched.tsv'], { encoding: 'utf8' }).trim() ? '+' : ''); } catch {}
  csv.push([today, head, T.funcs, fns.length, T.bytes, TOTAL_BYTES, pct(T.bytes, TOTAL_BYTES)].join(','));
  writeFileSync('progress.csv', csv.join('\n') + '\n');
}
const hist = csv.slice(1).map(l => l.split(','));

// per module
const mods = new Map();
for (const f of fns) {
  const m = mods.get(f.module) ?? { module: f.module, total: 0, bytes: 0, funcs: 0, exactF: 0, exactB: 0, inferred: 0 };
  m.funcs++; m.total += f.size; if (f.inferred) m.inferred++;
  if (exact.has(f.addr)) { m.exactF++; m.exactB += f.size; }
  mods.set(f.module, m);
}
// per size bucket
const buckets = [[0, 100], [101, 300], [301, 600], [601, 1000], [1001, 2000], [2001, Infinity]].map(([lo, hi]) => {
  const fs = fns.filter(f => f.size >= lo && f.size <= hi), ex = fs.filter(f => exact.has(f.addr));
  return { label: hi === Infinity ? `> ${lo - 1} B` : `${lo}–${hi} B`, funcs: fs.length, exactF: ex.length, total: fs.reduce((n, f) => n + f.size, 0), exactB: ex.reduce((n, f) => n + f.size, 0) };
});

const md = [];
md.push('# THPS1 matching decompilation: progress', '');
md.push(`_Generated by \`node tools/progress.mjs\` on ${today} from \`matched.tsv\`. Don't edit by hand. \`node tools/check_all.mjs\` re-verifies every counted function byte-for-byte against the retail executable._`, '');
md.push(`**${pct(T.bytes, TOTAL_BYTES)}%** of game code is byte-exact: **${T.bytes.toLocaleString('en-US')} / ${TOTAL_BYTES.toLocaleString('en-US')} bytes**, **${T.funcs} / ${fns.length} functions**.`, '');
md.push(`${bar(T.bytes, TOTAL_BYTES, 40)} ${pct(T.bytes, TOTAL_BYTES)}% of bytes`, `${bar(T.funcs, fns.length, 40)} ${pct(T.funcs, fns.length)}% of functions`, '');
md.push(`Scope: retail \`SLUS_008.60\` game code, 0x80010000–0x800858ac (${fns.length} functions from \`functions.tsv\`). The Psy-Q libraries linked after it are out of scope because the runtime/HLE provides them.`, '');

md.push('## History', '', '| date | commit | functions | bytes | % of bytes |', '|---|---|---:|---:|---:|');
const shown = hist.length > 15 ? [hist[0], ...hist.slice(-14)] : hist;
for (const h of shown) md.push(`| ${h[0]} | ${h[1]} | ${h[2]} | ${(+h[4]).toLocaleString('en-US')} | ${h[6]}% |`);
if (hist.length > 15) md.push('', `_(${hist.length} points in total; full series in \`progress.csv\`)_`);
md.push('');

md.push('## By size', '', '| function size | functions exact | bytes exact | |', '|---|---:|---:|---|');
for (const b of buckets) md.push(`| ${b.label} | ${b.exactF} / ${b.funcs} | ${kb(b.exactB)} / ${kb(b.total)} (${pct(b.exactB, b.total)}%) | ${bar(b.exactB, b.total)} |`);
md.push('');

md.push('## By module', '', "Module = source file from the demo's debug symbols. Unnamed functions (no demo symbol) are assigned to the preceding named function's module, since object files link contiguously. Treat modules with many unnamed members as approximate: they're often THPS1-only code with no demo counterpart.", '');
md.push('| module | functions | unnamed | bytes | % of bytes | |', '|---|---:|---:|---:|---:|---|');
for (const m of [...mods.values()].sort((a, b) => b.total - a.total))
  md.push(`| ${m.module} | ${m.exactF} / ${m.funcs} | ${m.inferred} | ${kb(m.exactB)} / ${kb(m.total)} | ${pct(m.exactB, m.total)}% | ${bar(m.exactB, m.total, 12)} |`);
md.push('');

md.push('## Closest near-misses', '', 'From `nearmiss.tsv` (the score is the better of positional and alignment-aware).', '', '| function | size | score | source |', '|---|---:|---:|---|');
for (const n of near.sort((a, b) => b.frac - a.frac || b.size - a.size).slice(0, 15))
  md.push(`| ${byAddr.get(n.addr)?.name ?? n.addr} | ${n.size} | ${n.score} (${(100 * n.frac).toFixed(1)}%) | \`${n.src}\` |`);
md.push('');

md.push('## Biggest unmatched functions', '', '| function | module | size | attempt |', '|---|---|---:|---|');
const nearBy = new Map(near.map(n => [n.addr, n]));
for (const f of fns.filter(f => !exact.has(f.addr)).sort((a, b) => b.size - a.size).slice(0, 15))
  md.push(`| ${f.name} (${f.addr}) | ${f.module}${f.inferred ? ' (inferred)' : ''} | ${kb(f.size)} | ${nearBy.has(f.addr) ? nearBy.get(f.addr).score : '—'} |`);
md.push('');

writeFileSync('PROGRESS.md', md.join('\n'));
console.log(`${T.funcs}/${fns.length} functions, ${T.bytes}/${TOTAL_BYTES} bytes (${pct(T.bytes, TOTAL_BYTES)}%) -> PROGRESS.md`);
